type RuleBody = Omit<MockRule, 'id' | 'enabled' | 'name'>
type MockInput = Omit<MockRule, 'id' | 'enabled'> & { id?: string }

export class AddonMissingError extends ToolError {}

type Row = typeof mitmMock.$inferSelect

function toRule(row: Row): MockRule {
  return { ...(JSON.parse(row.ruleJson) as RuleBody), id: row.id, name: row.name, enabled: row.enabled }
}

function getRow(id: string): Row {
  const row = getDb().select().from(mitmMock).where(eq(mitmMock.id, id)).get()
  if (!row) throw new ToolError(t`No rule ${id} — check mitm_mocks`)
  return row
}

/** Oldest first, then by id: the order the addon tries rules in. */
export function listMocks(): MockRule[] {
  return getDb().select().from(mitmMock).orderBy(asc(mitmMock.createdAt), asc(mitmMock.id)).all().map(toRule)
}

/** New rules start enabled; saving with an existing id replaces the rule and keeps its enabled flag. */
export function saveMock(input: MockInput): MockRule {
  const { id: given, name, ...rest } = input
  const body: Record<string, unknown> = { ...rest }
  delete body.enabled
  const ruleJson = JSON.stringify(body)
  const now = new Date()
  if (given) {
    // Ids are generated by the hub only: an unknown id is a mistake, not a request for a new rule.
    const existing = getDb().select().from(mitmMock).where(eq(mitmMock.id, given)).get()
    if (!existing) throw new ToolError(t`No rule ${given} — check mitm_mocks`)
    getDb().update(mitmMock).set({ name, ruleJson, updatedAt: now }).where(eq(mitmMock.id, existing.id)).run()
    return toRule(getRow(existing.id))
  }
  const id = randomUUID().slice(0, 8)
  getDb().insert(mitmMock).values({ id, name, enabled: true, ruleJson, createdAt: now, updatedAt: now }).run()
  return toRule(getRow(id))
}

export function setMockEnabled(id: string, enabled: boolean): MockRule {
  getRow(id)
  getDb().update(mitmMock).set({ enabled, updatedAt: new Date() }).where(eq(mitmMock.id, id)).run()
  return toRule(getRow(id))
}

export function deleteMock(id: string): void {
  getDb().delete(mitmMock).where(eq(mitmMock.id, id)).run()
}

export function deleteAllMocks(): number {
  return getDb().delete(mitmMock).run().changes
}

const ADDON_MISSING =
  'The hub_mocks.py addon is not loaded in mitmproxy: put it into Docker/mitmproxy/scripts/ and add `-s /scripts/hub_mocks.py` to command'

type Edit = { seq: number; op: 'enable' | 'disable' | 'delete'; id: string }
type Cursor = { epoch: string; lastSeq: number }

const CURSOR_KEY = 'mitm_edits_cursor'

function parseJournal(raw: unknown): { epoch: string; edits: Edit[] } | null {
  if (typeof raw !== 'string' || !raw) return null
  try {
    const data = JSON.parse(raw) as { epoch?: unknown; edits?: unknown }
    if (typeof data.epoch !== 'string' || !Array.isArray(data.edits)) return null
    const edits = data.edits.filter(
      (e): e is Edit =>
        typeof e === 'object' && e !== null &&
        typeof (e as Edit).seq === 'number' && typeof (e as Edit).id === 'string' &&
        ['enable', 'disable', 'delete'].includes((e as Edit).op),
    )
    return { epoch: data.epoch, edits }
  } catch {
    return null
  }
}

function readCursor(): Cursor | null {
  try {
    const c = JSON.parse(getSetting(CURSOR_KEY) ?? 'null') as Cursor | null
    return c && typeof c.epoch === 'string' && typeof c.lastSeq === 'number' ? c : null
  } catch {
    return null
  }
}

/**
 * Apply changes made with the mitmweb commands (option `hub_mocks_edits`) that the hub has not seen:
 * newer than the stored cursor for the same addon epoch, all of them for a new epoch. The journal
 * is never cleared on the proxy; the cursor alone keeps edits from applying twice. While mocks are
 * not allowed the edits are skipped, but the cursor still moves so they never apply later.
 */
function applyEdits(raw: unknown, allowed: boolean): void {
  const journal = parseJournal(raw)
  if (!journal || journal.edits.length === 0) return
  const cursor = readCursor()
  const after = cursor?.epoch === journal.epoch ? cursor.lastSeq : 0
  const fresh = journal.edits.filter((e) => e.seq > after).sort((a, b) => a.seq - b.seq)
  if (fresh.length === 0) return
  if (allowed) {
    for (const e of fresh) {
      try {
        if (e.op === 'delete') deleteMock(e.id)
        else setMockEnabled(e.id, e.op === 'enable')
      } catch (err) {
        if (!(err instanceof ToolError)) throw err // unknown id: deleted in the hub meanwhile
      }
    }
  }
  setSetting(CURSOR_KEY, JSON.stringify({ epoch: journal.epoch, lastSeq: fresh.at(-1)!.seq }))
}

// Last known reachability, so a down proxy is logged once rather than every minute.
let reachable = true

type SyncResult = 'in-sync' | 'pushed' | 'skipped'

// Syncs run one at a time, each reading the rules inside the lock, so an older (cron) PUT can never
// land after a newer (tool) one.
let queue: Promise<unknown> = Promise.resolve()

/** Apply edits made in mitmweb, then push the desired rules if the proxy differs. Non-strict mode never throws (used by the cron job). */
export function syncMocks(opts: { strict?: boolean } = {}): Promise<SyncResult> {
  const run = queue.then(() => syncOnce(opts))
  queue = run.catch(() => undefined)
  return run
}

/**
 * A hub-side change to the rules, made inside the sync queue after pending mitmweb edits are applied, so an
 * older mitmweb edit never lands on top of it (and a rule deleted in mitmweb is not resurrected). Errors from
 * `mutate` propagate and nothing is pushed; a failed push after a successful change comes back as `failure`.
 */
export function mutateMocks<T>(mutate: () => T): Promise<{ value: T; failure: string | null }> {
  const run = queue.then(async () => {
    // Widened on purpose: TS cannot see the assignment inside the callback.
    let done = undefined as { value: T } | undefined
    let failure: string | null = null
    try {
      await syncOnce({ strict: true }, () => {
        done = { value: mutate() }
      })
    } catch (e) {
      if (!done || !(e instanceof ToolError)) throw e
      failure = e.message
    }
    return { value: done!.value, failure }
  })
  queue = run.catch(() => undefined)
  return run
}

async function syncOnce(opts: { strict?: boolean }, mutate?: () => void): Promise<SyncResult> {
  const connector = getConnector('mitmproxy')
  const row = getConnectorRow('mitmproxy')
  const parsed = connector && row ? connector.parseConfig(readConfig(connector, row)) : null
  if (!row || !parsed?.ok) {
    mutate?.()
    return 'skipped'
  }
  const config = parsed.config as { baseUrl: string; password?: string; timeoutSec: number; allowMocks: boolean }

  const allowed = row.enabled && config.allowMocks
  const client = new MitmClient({ baseUrl: config.baseUrl, password: config.password, timeoutSec: config.timeoutSec })
  let options: Record<string, { value: unknown }> | null = null
  let failed: unknown = null
  try {
    options = await client.options()
    reachable = true
    applyEdits(options.hub_mocks_edits?.value, allowed)
  } catch (e) {
    failed = e
  }
  // The hub change is stored even when the proxy is down; its own errors are not sync errors.
  mutate?.()
  try {
    if (failed) throw failed
    const current = options?.hub_mocks
    if (!current) throw new AddonMissingError(tr(ADDON_MISSING))
    const desired = payloadFor(allowed ? listMocks() : [], allowed, getLang())
    if (current.value === desired) return 'in-sync'
    await client.setOptions({ hub_mocks: desired })
    return 'pushed'
  } catch (e) {
    if (opts.strict) throw e
    if (e instanceof AddonMissingError) return 'skipped'
    if (reachable) logger.warn({ err: e instanceof Error ? e.message : String(e) }, 'mitmproxy unreachable, mocks not synced')
    reachable = false
    return 'skipped'
  }
}
